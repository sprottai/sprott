//! `version`, `git-credential get` and `serve` against a home holding a 1.5
//! `~/.safeclaw` (and its unit): nothing is moved, nothing is created, and
//! `serve` exits 0 (design 2.0 §4 "serve", dev matrix V9).
//!
//! The binary runs with a cleared environment: HOME and XDG_CONFIG_HOME point
//! into a temp dir, and PATH holds only fake `systemctl` / `launchctl` that log
//! and fail, so no run can reach the real user bus or daemon.

use std::collections::BTreeMap;
use std::fs;
use std::io::Write as _;
use std::path::Path;
use std::process::{Command, Output, Stdio};
use std::time::{Duration, Instant};

fn put(path: &Path, text: &str) {
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, text).unwrap();
}

fn snapshot(dir: &Path) -> BTreeMap<String, Vec<u8>> {
    fn walk(dir: &Path, base: &Path, out: &mut BTreeMap<String, Vec<u8>>) {
        for e in fs::read_dir(dir).unwrap().flatten() {
            let p = e.path();
            let rel = p.strip_prefix(base).unwrap().display().to_string();
            let meta = fs::symlink_metadata(&p).unwrap();
            if meta.file_type().is_symlink() {
                out.insert(rel, fs::read_link(&p).unwrap().display().to_string().into_bytes());
            } else if meta.is_dir() {
                out.insert(format!("{rel}/"), Vec::new());
                walk(&p, base, out);
            } else {
                out.insert(rel, fs::read(&p).unwrap());
            }
        }
    }
    let mut out = BTreeMap::new();
    walk(dir, dir, &mut out);
    out
}

fn run(home: &Path, bin: &Path, args: &[&str], stdin: &str) -> Output {
    let mut child = Command::new(env!("CARGO_BIN_EXE_sprott"))
        .args(args)
        .env_clear()
        .env("HOME", home)
        .env("XDG_CONFIG_HOME", home.join(".config"))
        .env("PATH", bin)
        // Ports nothing listens on (and that need root to bind).
        .env("SPROTT_PORT", "1")
        .env("SPROTT_PROXY_PORT", "2")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .unwrap();
    child.stdin.take().unwrap().write_all(stdin.as_bytes()).unwrap();
    let start = Instant::now();
    while child.try_wait().unwrap().is_none() {
        if start.elapsed() > Duration::from_secs(30) {
            let _ = child.kill();
            panic!("sprott {args:?} did not exit");
        }
        std::thread::sleep(Duration::from_millis(50));
    }
    child.wait_with_output().unwrap()
}

#[cfg(unix)]
#[test]
fn version_git_credential_and_serve_leave_a_1_5_home_alone() {
    use std::os::unix::fs::PermissionsExt;
    let tmp = tempfile::tempdir().unwrap();
    let home = tmp.path().join("home");
    let bin = tmp.path().join("bin");
    let calls = tmp.path().join("calls.log");
    for tool in ["systemctl", "launchctl"] {
        let p = bin.join(tool);
        put(
            &p,
            &format!("#!/bin/sh\necho \"{tool} $*\" >> '{}'\nexit 1\n", calls.display()),
        );
        fs::set_permissions(&p, fs::Permissions::from_mode(0o755)).unwrap();
    }

    let h = home.display();
    put(
        &home.join(".safeclaw/config.toml"),
        "daemon = \"http://127.0.0.1:1\"\nvault = \"v1\"\n",
    );
    put(
        &home.join(".safeclaw/agents/codex/agent.env"),
        &format!("SAFECLAW_BROKER_URL=http://127.0.0.1:2\nSAFECLAW_AGENT_IDENTITY={h}/.safeclaw/agents/codex/identity\n"),
    );
    put(&home.join(".safeclaw/state/egress-proxy"), "http://proxy.example:3128\n");
    put(
        &home.join(".config/systemd/user/safeclaw.service"),
        &format!("# Generated by safeclaw. Do not edit; re-run `sprott up` to refresh.\n[Service]\nExecStart={h}/.local/bin/sc serve\n"),
    );
    let before = snapshot(&home);

    let out = run(&home, &bin, &["version"], "");
    assert!(out.status.success(), "{out:?}");
    assert!(String::from_utf8_lossy(&out.stdout).starts_with("sprott "));

    let out = run(
        &home,
        &bin,
        &["git-credential", "get"],
        "protocol=https\nhost=github.com\n\n",
    );
    assert!(out.status.success(), "{out:?}");
    assert!(out.stdout.is_empty(), "{out:?}");

    let out = run(&home, &bin, &["serve"], "");
    assert!(out.status.success(), "{out:?}");
    assert!(
        String::from_utf8_lossy(&out.stderr).contains(
            "Sprott 2.0 needs one sprott command to finish moving ~/.safeclaw (run: sprott up)"
        ),
        "{out:?}"
    );

    assert!(!home.join(".sprott").exists());
    assert!(!home.join(".sprott-migrate.lock").exists());
    assert_eq!(snapshot(&home), before, "~/.safeclaw and the unit are byte-identical");
    assert!(!calls.exists(), "no service manager was called");
}

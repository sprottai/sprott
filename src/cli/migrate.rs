//! 2.0: the one-time move of a 1.x install to the 2.0 names.
//!
//! 1.x kept everything under `~/.safeclaw` and ran the daemon as
//! `safeclaw.service` (Linux) or `pro.safeclaw.daemon` (macOS). The first
//! ordinary 2.0 command, right after argument parsing, stops that daemon,
//! renames the directory to `~/.sprott` (one atomic rename), rewrites the files
//! 1.x generated with old names (agent.env files, the setup status, the unit or
//! plist) and starts the daemon again if it was running. Every step after the
//! rename is idempotent, so a kill at any point is finished by the next
//! command.
//!
//! This is the only module that reads a pre-2.0 path or name, and only to move
//! it. `version`, `git-credential` and `serve` never run it; `serve` refuses to
//! start while a move is pending ([`serve_must_wait`]). It never merges two
//! directories, deletes user data, edits files outside `~/.sprott` other than
//! the unit or plist, or touches vault items, keys or the CA.
//!
//! Delete in 2.1 (design/compat-sunset.md).

use std::fs::{self, OpenOptions};
use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::time::Duration;

use serde::{Deserialize, Serialize};

use crate::config::Command;
use crate::names;

const OLD_DIR: &str = ".safeclaw";
const OLD_ENV_PREFIX: &str = "SAFECLAW_";
const NEW_ENV_PREFIX: &str = "SPROTT_";
const OLD_UNIT: &str = "safeclaw.service";
const OLD_UNIT_MARKER: &str = "# Generated by safeclaw";
const NEW_UNIT_MARKER: &str = "# Generated by sprott";
const OLD_LABEL: &str = "pro.safeclaw.daemon";
const OLD_PLIST_MARKER: &str = "Generated by safeclaw";
const NEW_PLIST_MARKER: &str = "Generated by sprott";
/// Written into `~/.safeclaw` before the daemon is stopped; it travels with
/// the rename and marks state B until the move is finished.
const MOVING: &str = ".moving-from-safeclaw";
/// `~/.sprott/<RECORD>` once the move is finished.
const RECORD: &str = "migrated-from-safeclaw.json";
/// `~/.sprott/<PRE_2>/`: the originals of every file the move rewrote or
/// moved out of the way.
const PRE_2: &str = "pre-2.0";
/// `~/<LOCK>`: two commands started together move once.
const LOCK: &str = ".sprott-migrate.lock";

const POLL: Duration = Duration::from_millis(250);

// ── state ────────────────────────────────────────────────────────────────────

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum State {
    /// `~/.safeclaw` is a directory and `~/.sprott` is absent: move it.
    A,
    /// `~/.sprott/.moving-from-safeclaw` exists: moved, not finished.
    B,
    /// Finished, and a binary from before 2.0 recreated `~/.safeclaw` since:
    /// ignored (`sprott doctor` reports it).
    C,
    /// Both exist and `~/.sprott` did not come from a move: refuse.
    D,
    /// Nothing to move: a fresh install, or finished.
    E,
}

pub(crate) fn detect(home: &Path) -> State {
    let new = names::data_dir_in(home);
    if fs::symlink_metadata(new.join(MOVING)).is_ok() {
        return State::B;
    }
    let old = home.join(OLD_DIR);
    if !fs::metadata(&old).map(|m| m.is_dir()).unwrap_or(false) {
        return State::E;
    }
    if fs::symlink_metadata(&new).is_err() {
        return State::A;
    }
    if new.join(RECORD).exists() {
        State::C
    } else {
        State::D
    }
}

/// Two `lstat`s: no `~/.safeclaw` and no unfinished move.
fn nothing_to_do(home: &Path) -> bool {
    fs::symlink_metadata(home.join(OLD_DIR)).is_err()
        && fs::symlink_metadata(names::data_dir_in(home).join(MOVING)).is_err()
}

/// `serve` must not start while `~/.safeclaw` waits to be moved (state A) or
/// the move is refused (state D): a daemon would create `~/.sprott` with fresh
/// keys and turn A into D for good. In state B the directory has moved, so it
/// serves normally.
pub fn serve_must_wait(home: &Path) -> bool {
    !nothing_to_do(home) && matches!(detect(home), State::A | State::D)
}

pub const SERVE_WAIT_MSG: &str =
    "Sprott 2.0 needs one sprott command to finish moving ~/.safeclaw (run: sprott up)";

// ── the outside world ────────────────────────────────────────────────────────

/// The service managers, processes and ports the move talks to. Tests swap in
/// a fake so no test reaches the real user bus or a real daemon.
pub(crate) trait Sys: Sync {
    /// Something answers a TCP connect on `authority` (`host:port`).
    fn answers(&self, authority: &str) -> bool;
    fn pid_live(&self, pid: u32) -> bool;
    /// SIGTERM.
    fn terminate(&self, pid: u32);
    /// `systemctl --user <args>`.
    fn systemctl(&self, args: &[&str]) -> Result<(), String>;
    /// `launchctl <args>`.
    fn launchctl(&self, args: &[&str]) -> Result<(), String>;
    /// Start `<exe> serve` detached, with its pid and log in `~/.sprott`.
    fn spawn_detached(&self, exe: &Path) -> Result<(), String>;
    fn uid(&self) -> u32;
    fn sleep(&self, d: Duration);
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Platform {
    Systemd,
    Launchd,
    Neither,
}

impl Platform {
    fn current() -> Self {
        if cfg!(target_os = "linux") {
            Platform::Systemd
        } else if cfg!(target_os = "macos") {
            Platform::Launchd
        } else {
            Platform::Neither
        }
    }
}

/// Points where a test kills the move (the process dies; nothing is undone).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Step {
    /// After steps 1-4 (stopped), before the rename.
    Stopped,
    /// After step 6 (renamed).
    Moved,
    /// After step 7.
    AgentEnv,
    /// After step 8.
    Status,
    /// Inside step 9: the new unit or plist written, the old one still there.
    UnitWritten,
    /// After step 9.
    Service,
    /// After step 10, before step 11.
    Started,
    /// Inside step 11: the record written into the marker, not yet renamed.
    RecordWritten,
}

pub(crate) struct Ctx<'a> {
    pub home: PathBuf,
    /// `$XDG_CONFIG_HOME/systemd/user`.
    pub unit_dir: PathBuf,
    /// `~/Library/LaunchAgents`.
    pub launch_agents: PathBuf,
    pub platform: Platform,
    /// The binary the new unit or plist runs, symlinks resolved.
    pub exe: PathBuf,
    pub sys: &'a dyn Sys,
    /// Step 10: start the daemon again if it was running. Off for the commands
    /// that start or stop it right after (`up`, `restart`, `down`).
    pub start_daemon: bool,
    /// How long to wait for a daemon to stop or answer.
    pub wait: Duration,
    /// Test hook: stop dead after this step, as a kill would.
    pub crash_after: Option<Step>,
}

impl Ctx<'_> {
    fn checkpoint(&self, step: Step) -> Result<(), Fail> {
        if self.crash_after == Some(step) {
            Err(Fail::Crashed)
        } else {
            Ok(())
        }
    }

    fn wait_until(&self, mut done: impl FnMut() -> bool) -> bool {
        let rounds = (self.wait.as_millis() / POLL.as_millis()).max(1);
        for _ in 0..rounds {
            if done() {
                return true;
            }
            self.sys.sleep(POLL);
        }
        done()
    }

    fn gui(&self, label: &str) -> String {
        format!("gui/{}/{}", self.sys.uid(), label)
    }

    fn data(&self) -> PathBuf {
        names::data_dir_in(&self.home)
    }

    fn old_unit(&self) -> Option<PathBuf> {
        let p = self.unit_dir.join(OLD_UNIT);
        (self.platform == Platform::Systemd && p.exists()).then_some(p)
    }

    fn old_plist(&self) -> Option<PathBuf> {
        let p = self.launch_agents.join(format!("{OLD_LABEL}.plist"));
        (self.platform == Platform::Launchd && p.exists()).then_some(p)
    }

    fn new_plist(&self) -> PathBuf {
        self.launch_agents
            .join(format!("{}.plist", names::LAUNCHD_LABEL))
    }
}

#[derive(Debug)]
pub(crate) enum Fail {
    /// Phase 1 refused or failed: nothing moved, the command must not run.
    Refused(String),
    /// A test kill.
    Crashed,
}

#[derive(Debug, PartialEq, Eq)]
pub(crate) enum Outcome {
    Nothing,
    Moved(Report),
    /// Moved, but phase 2 stopped at an error; the next command retries it.
    Unfinished(String),
}

#[derive(Debug, Default, PartialEq, Eq)]
pub(crate) struct Report {
    /// The unit or plist now runs the daemon.
    pub service: Option<Platform>,
    /// Things the move left as they were, one sentence each.
    pub left: Vec<String>,
    /// Step 10 started the daemon but it did not answer.
    pub not_started: bool,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "lowercase")]
enum Manager {
    Systemd,
    Launchd,
    Detached,
    #[default]
    None,
}

/// The marker's content: how the old daemon ran, so step 10 can start the new
/// one the same way.
#[derive(Debug, Clone, Serialize, Deserialize, Default, PartialEq, Eq)]
struct Moving {
    #[serde(default)]
    was_running: bool,
    #[serde(default)]
    was_enabled: bool,
    #[serde(default)]
    manager: Manager,
    #[serde(default)]
    binary: String,
    #[serde(default)]
    at: u64,
}

#[derive(Serialize)]
struct Record<'a> {
    #[serde(flatten)]
    moving: &'a Moving,
    finished_at: u64,
    /// Paths under `pre-2.0/`: the originals of what the move rewrote.
    rewritten: Vec<String>,
    left: &'a [String],
}

// ── entry points ─────────────────────────────────────────────────────────────

/// The commands that never move anything: `version` is a pure read (the
/// upgrader parses its output), `git-credential` must stay silent and
/// side-effect free, and `serve` has its own check ([`serve_must_wait`]).
pub fn exempt(cmd: &Command) -> bool {
    matches!(
        cmd,
        Command::Version | Command::GitCredential(_) | Command::Serve(_)
    )
}

/// Run from `run_cli` right after parsing. `Err` is the message to print; the
/// command must not run then.
pub fn before_command(cmd: &Command) -> Result<(), String> {
    if exempt(cmd) {
        return Ok(());
    }
    let Some(home) = dirs::home_dir() else {
        return Ok(());
    };
    if nothing_to_do(&home) {
        return Ok(());
    }
    let exe = crate::cli::service::service_binary()?;
    let sys = RealSys;
    let ctx = Ctx {
        unit_dir: dirs::config_dir()
            .unwrap_or_else(|| home.join(".config"))
            .join("systemd/user"),
        launch_agents: home.join("Library/LaunchAgents"),
        home,
        platform: Platform::current(),
        exe,
        sys: &sys,
        start_daemon: !matches!(cmd, Command::Up | Command::Restart | Command::Down),
        wait: Duration::from_secs(20),
        crash_after: None,
    };
    match run(&ctx) {
        Ok(Outcome::Nothing) => Ok(()),
        Ok(Outcome::Moved(report)) => {
            for line in report_lines(&report) {
                eprintln!("{line}");
            }
            Ok(())
        }
        Ok(Outcome::Unfinished(e)) => {
            eprintln!(
                "Sprott 2.0 moved ~/.safeclaw to ~/.sprott but could not finish: {e}. \
                 The next sprott command tries again."
            );
            Ok(())
        }
        Err(Fail::Refused(msg)) => Err(msg),
        Err(Fail::Crashed) => Err("interrupted".to_string()),
    }
}

pub(crate) fn report_lines(report: &Report) -> Vec<String> {
    let mut out = vec![match report.service {
        Some(Platform::Systemd) => format!(
            "Moved ~/.safeclaw to ~/.sprott; the daemon is now {}.",
            names::SYSTEMD_UNIT
        ),
        Some(Platform::Launchd) => format!(
            "Moved ~/.safeclaw to ~/.sprott; the daemon is now {}.",
            names::LAUNCHD_LABEL
        ),
        _ => "Moved ~/.safeclaw to ~/.sprott.".to_string(),
    }];
    out.extend(report.left.iter().cloned());
    if report.not_started {
        out.push("The daemon did not start after the move; run: sprott up".to_string());
    }
    out
}

pub(crate) fn run(ctx: &Ctx) -> Result<Outcome, Fail> {
    if matches!(detect(&ctx.home), State::C | State::E) {
        return Ok(Outcome::Nothing);
    }
    let lock = Lock::take(&ctx.home).map_err(Fail::Refused)?;
    // Another command may have moved it while this one waited for the lock.
    match detect(&ctx.home) {
        State::C | State::E => {
            lock.release_finished();
            return Ok(Outcome::Nothing);
        }
        State::D => {
            return Err(Fail::Refused(
                "Sprott 2.0 could not move ~/.safeclaw: ~/.sprott already exists and did not come from it.\n\
                 Fix: move ~/.sprott aside, then run: sprott up"
                    .to_string(),
            ))
        }
        State::A => phase1(ctx)?,
        State::B => {}
    }
    match phase2(ctx) {
        Ok(report) => {
            lock.release_finished();
            Ok(Outcome::Moved(report))
        }
        Err(Phase2::Failed(e)) => Ok(Outcome::Unfinished(e)),
        Err(Phase2::Crashed) => Err(Fail::Crashed),
    }
}

// ── phase 1: stop, then move ─────────────────────────────────────────────────

fn phase1(ctx: &Ctx) -> Result<(), Fail> {
    let old = ctx.home.join(OLD_DIR);
    let marker = old.join(MOVING);
    // 1. The old daemon: its control port, its pid file, its unit or plist.
    let control = control_authority(&old);
    let pid = read_pid(&old.join("daemon.pid")).filter(|p| ctx.sys.pid_live(*p));
    let unit = ctx.old_unit();
    let plist = ctx.old_plist();

    // 2. How it ran. A marker left by an earlier attempt that was killed after
    //    the stop still says the daemon was running, so it comes back at the end.
    let previous: Option<Moving> = read_json(&marker);
    let mut moving = Moving {
        was_running: pid.is_some() || ctx.sys.answers(&control),
        was_enabled: if unit.is_some() {
            fs::symlink_metadata(ctx.unit_dir.join("default.target.wants").join(OLD_UNIT)).is_ok()
        } else {
            plist.is_some()
        },
        manager: if pid.is_some() {
            Manager::Detached
        } else if unit.is_some() {
            Manager::Systemd
        } else if plist.is_some() {
            Manager::Launchd
        } else {
            Manager::None
        },
        binary: ctx.exe.display().to_string(),
        at: crate::util::now_unix(),
    };
    if let Some(p) = &previous {
        moving.was_running |= p.was_running;
        moving.was_enabled |= p.was_enabled;
        if moving.manager == Manager::None {
            moving.manager = p.manager;
        }
    }
    // 5 (before the stop, see above). It travels with the rename.
    write_json(&marker, &moving)
        .map_err(|e| Fail::Refused(format!("Sprott 2.0 could not move ~/.safeclaw: {e}")))?;

    // 3. Stop it the way it was started.
    let mut stopped_unit = false;
    if unit.is_some() {
        stopped_unit = ctx.sys.systemctl(&["stop", OLD_UNIT]).is_ok();
    }
    if plist.is_some() {
        let _ = ctx.sys.launchctl(&["bootout", &ctx.gui(OLD_LABEL)]);
    }
    if let Some(p) = pid {
        ctx.sys.terminate(p);
    }

    // 4. Wait for silence.
    let silent =
        ctx.wait_until(|| !ctx.sys.answers(&control) && !pid.is_some_and(|p| ctx.sys.pid_live(p)));
    let undo = |ctx: &Ctx| {
        if moving.was_running {
            if stopped_unit {
                let _ = ctx.sys.systemctl(&["start", OLD_UNIT]);
            }
            if let Some(p) = &plist {
                let domain = format!("gui/{}", ctx.sys.uid());
                let _ = ctx
                    .sys
                    .launchctl(&["bootstrap", &domain, &p.to_string_lossy()]);
            }
        }
        match &previous {
            Some(p) => {
                let _ = write_json(&marker, p);
            }
            None => {
                let _ = fs::remove_file(&marker);
            }
        }
    };
    if !silent {
        undo(ctx);
        let who = match pid.filter(|p| ctx.sys.pid_live(*p)) {
            Some(p) => format!("pid {p}"),
            None => format!("http://{control}"),
        };
        return Err(Fail::Refused(format!(
            "Sprott 2.0 could not move ~/.safeclaw: a daemon from before 2.0 is still running ({who}).\n\
             Fix: stop it, then run: sprott up"
        )));
    }
    ctx.checkpoint(Step::Stopped)?;

    // 6. One rename: same file system, atomic, instant for any size. A
    //    symlinked ~/.safeclaw moves as the symlink.
    if let Err(e) = fs::rename(&old, ctx.data()) {
        undo(ctx);
        return Err(Fail::Refused(format!(
            "Sprott 2.0 could not move ~/.safeclaw to ~/.sprott: {e}"
        )));
    }
    ctx.checkpoint(Step::Moved)?;
    Ok(())
}

// ── phase 2: finish (every step idempotent) ──────────────────────────────────

enum Phase2 {
    Failed(String),
    Crashed,
}

impl From<Fail> for Phase2 {
    fn from(f: Fail) -> Self {
        match f {
            Fail::Crashed => Phase2::Crashed,
            Fail::Refused(e) => Phase2::Failed(e),
        }
    }
}

impl From<String> for Phase2 {
    fn from(e: String) -> Self {
        Phase2::Failed(e)
    }
}

fn phase2(ctx: &Ctx) -> Result<Report, Phase2> {
    let data = ctx.data();
    let moving: Moving = read_json(&data.join(MOVING)).unwrap_or_default();
    let control = control_authority(&data);
    // A daemon serving already: the old unit started this binary after a crash
    // (the swap below stops it), or step 10 ran before a kill.
    let serving = ctx.sys.answers(&control);
    let mut left = Vec::new();

    // 7. agent.env files.
    for file in agent_env_files(&data) {
        rewrite_agent_env(&ctx.home, &data, &file, &mut left)?;
    }
    ctx.checkpoint(Step::AgentEnv)?;

    // 8. setup status.
    rewrite_setup_status(&ctx.home, &data)?;
    ctx.checkpoint(Step::Status)?;

    // 9. The unit or plist.
    let service = match ctx.platform {
        Platform::Systemd => swap_unit(ctx, &data, &moving, &mut left)?,
        Platform::Launchd => swap_plist(ctx, &data, &mut left)?,
        Platform::Neither => None,
    };
    ctx.checkpoint(Step::Service)?;

    // A detached daemon stays detached, even beside a unit file 1.x wrote
    // before it found no user systemd.
    let service = if moving.manager == Manager::Detached {
        None
    } else {
        service
    };

    // 10. Run state.
    let mut not_started = false;
    if ctx.start_daemon && (moving.was_running || serving) && !ctx.sys.answers(&control) {
        start_daemon(ctx, service, &moving);
        not_started = !ctx.wait_until(|| ctx.sys.answers(&control));
    }
    ctx.checkpoint(Step::Started)?;

    // 11. The record.
    let record = Record {
        moving: &moving,
        finished_at: crate::util::now_unix(),
        rewritten: files_under(&data.join(PRE_2)),
        left: &left,
    };
    write_json(&data.join(MOVING), &record)?;
    ctx.checkpoint(Step::RecordWritten)?;
    fs::rename(data.join(MOVING), data.join(RECORD))
        .map_err(|e| format!("rename {}: {e}", data.join(MOVING).display()))?;

    Ok(Report {
        service,
        left,
        not_started,
    })
}

fn start_daemon(ctx: &Ctx, service: Option<Platform>, moving: &Moving) {
    match (service, moving.manager) {
        (_, Manager::Detached) => {
            let _ = ctx.sys.spawn_detached(&ctx.exe);
        }
        (Some(Platform::Systemd), _) => {
            let _ = ctx.sys.systemctl(&["start", names::SYSTEMD_UNIT]);
        }
        (Some(Platform::Launchd), _) => {
            // The verbs `sprott restart` converges with.
            let service = ctx.gui(names::LAUNCHD_LABEL);
            let domain = format!("gui/{}", ctx.sys.uid());
            let plist = ctx.new_plist().to_string_lossy().to_string();
            let _ = ctx.sys.launchctl(&["bootout", &service]);
            let _ = ctx.sys.launchctl(&["enable", &service]);
            let _ = ctx.sys.launchctl(&["bootstrap", &domain, &plist]);
            let _ = ctx.sys.launchctl(&["kickstart", "-k", &service]);
        }
        // A hand-written unit or plist was left in place: start it again.
        (_, Manager::Systemd) => {
            let _ = ctx.sys.systemctl(&["start", OLD_UNIT]);
        }
        (_, Manager::Launchd) => {
            let domain = format!("gui/{}", ctx.sys.uid());
            let plist = ctx.launch_agents.join(format!("{OLD_LABEL}.plist"));
            let _ = ctx
                .sys
                .launchctl(&["bootstrap", &domain, &plist.to_string_lossy()]);
        }
        (_, Manager::None) => {
            let _ = ctx.sys.spawn_detached(&ctx.exe);
        }
    }
}

fn swap_unit(
    ctx: &Ctx,
    data: &Path,
    moving: &Moving,
    left: &mut Vec<String>,
) -> Result<Option<Platform>, Phase2> {
    let old = ctx.unit_dir.join(OLD_UNIT);
    let new = ctx.unit_dir.join(names::SYSTEMD_UNIT);
    let backup = data.join(PRE_2).join(OLD_UNIT);
    // A systemctl failure stops phase 2 (the next command retries) only where
    // systemd ran the daemon. 1.x `sc up` writes the unit before it finds no
    // user systemd and falls back to a detached daemon; there it cannot work.
    let in_use = moving.manager == Manager::Systemd || moving.was_enabled;
    let systemctl = |args: &[&str]| -> Result<(), Phase2> {
        match ctx.sys.systemctl(args) {
            Err(e) if in_use => Err(e.into()),
            _ => Ok(()),
        }
    };
    match fs::read_to_string(&old) {
        Ok(text) if !text.contains(OLD_UNIT_MARKER) => {
            left.push(format!(
                "{} was not generated by sprott; it was left as it is.",
                tilde(&ctx.home, &old)
            ));
            return Ok(None);
        }
        Ok(text) => {
            if fs::read_to_string(&new).is_ok_and(|t| !t.contains(NEW_UNIT_MARKER)) {
                left.push(format!(
                    "{} was not generated by sprott; {} was left as it is.",
                    tilde(&ctx.home, &new),
                    tilde(&ctx.home, &old)
                ));
                return Ok(None);
            }
            let env = carry_unit_env(&text, &ctx.home);
            let unit = crate::cli::service::systemd_unit(&ctx.exe.to_string_lossy(), &env);
            write_atomic(&new, unit.as_bytes(), 0o600)?;
            ctx.checkpoint(Step::UnitWritten)?;
            systemctl(&["disable", "--now", OLD_UNIT])?;
            // Moved, not copied: it may hold a secret (Environment= lines).
            move_file(&old, &backup)?;
        }
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
        Err(e) => return Err(format!("read {}: {e}", old.display()).into()),
    }
    let swapped =
        backup.exists() && fs::read_to_string(&new).is_ok_and(|t| t.contains(NEW_UNIT_MARKER));
    if !swapped {
        return Ok(None);
    }
    systemctl(&["daemon-reload"])?;
    if moving.was_enabled {
        systemctl(&["enable", names::SYSTEMD_UNIT])?;
    }
    Ok(Some(Platform::Systemd))
}

fn swap_plist(ctx: &Ctx, data: &Path, left: &mut Vec<String>) -> Result<Option<Platform>, Phase2> {
    let old = ctx.launch_agents.join(format!("{OLD_LABEL}.plist"));
    let new = ctx.new_plist();
    let backup = data.join(PRE_2).join(format!("{OLD_LABEL}.plist"));
    match fs::read_to_string(&old) {
        Ok(text) if !text.contains(OLD_PLIST_MARKER) => {
            left.push(format!(
                "{} was not generated by sprott; it was left as it is.",
                tilde(&ctx.home, &old)
            ));
            return Ok(None);
        }
        Ok(text) => {
            if fs::read_to_string(&new).is_ok_and(|t| !t.contains(NEW_PLIST_MARKER)) {
                left.push(format!(
                    "{} was not generated by sprott; {} was left as it is.",
                    tilde(&ctx.home, &new),
                    tilde(&ctx.home, &old)
                ));
                return Ok(None);
            }
            let env = carry_plist_env(&text, &ctx.home);
            let log = data.join("daemon.log");
            let plist = crate::cli::service::launchd_plist(
                names::LAUNCHD_LABEL,
                &ctx.exe.to_string_lossy(),
                &env,
                &log.to_string_lossy(),
            );
            write_atomic(&new, plist.as_bytes(), 0o600)?;
            ctx.checkpoint(Step::UnitWritten)?;
            // Booted out in step 3; again here in case the old job came back.
            let _ = ctx.sys.launchctl(&["bootout", &ctx.gui(OLD_LABEL)]);
            move_file(&old, &backup)?;
        }
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
        Err(e) => return Err(format!("read {}: {e}", old.display()).into()),
    }
    let swapped =
        backup.exists() && fs::read_to_string(&new).is_ok_and(|t| t.contains(NEW_PLIST_MARKER));
    Ok(swapped.then_some(Platform::Launchd))
}

// ── rewriting ────────────────────────────────────────────────────────────────

/// `SAFECLAW_X` → `SPROTT_X`; any other key as it is.
fn rename_key(key: &str) -> String {
    match key.strip_prefix(OLD_ENV_PREFIX) {
        Some(rest) => format!("{NEW_ENV_PREFIX}{rest}"),
        None => key.to_string(),
    }
}

/// The two spellings of the old directory as a prefix, with their new forms.
fn dir_prefixes(home: &Path) -> [(String, String); 2] {
    let home = home.to_string_lossy();
    [
        (
            format!("{home}/{OLD_DIR}"),
            format!("{home}/{}", names::DATA_DIR),
        ),
        (format!("~/{OLD_DIR}"), format!("~/{}", names::DATA_DIR)),
    ]
}

/// A value that starts with `<home>/.safeclaw` or `~/.safeclaw` (followed by
/// `/` or nothing) starts with the new directory instead.
fn rewrite_leading_dir(value: &str, home: &Path) -> String {
    for (old, new) in dir_prefixes(home) {
        if let Some(rest) = value.strip_prefix(&old) {
            if rest.is_empty() || rest.starts_with('/') {
                return format!("{new}{rest}");
            }
        }
    }
    value.to_string()
}

/// Every `<home>/.safeclaw` or `~/.safeclaw` (followed by `/` or the end) in
/// `text` names the new directory.
fn rewrite_dir_anywhere(text: &str, home: &Path) -> String {
    let mut out = text.to_string();
    for (old, new) in dir_prefixes(home) {
        let mut result = String::with_capacity(out.len());
        let mut rest = out.as_str();
        while let Some(i) = rest.find(&old) {
            let after = &rest[i + old.len()..];
            result.push_str(&rest[..i]);
            if after.is_empty() || after.starts_with('/') {
                result.push_str(&new);
            } else {
                result.push_str(&old);
            }
            rest = after;
        }
        result.push_str(rest);
        out = result;
    }
    out
}

fn names_old(text: &str) -> bool {
    text.contains(OLD_ENV_PREFIX) || text.contains(&format!("/{OLD_DIR}"))
}

fn is_env_key(key: &str) -> bool {
    let mut chars = key.chars();
    chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

/// The value of `raw` if it is in a form `agent::env_value` writes: bare
/// path-safe characters, or single quotes with `'\''` for an inner quote.
fn unquote_env_value(raw: &str) -> Option<String> {
    if let Some(inner) = raw.strip_prefix('\'').and_then(|r| r.strip_suffix('\'')) {
        let value = inner.replace("'\\''", "'");
        let requoted = format!("'{}'", value.replace('\'', "'\\''"));
        return (requoted == raw).then_some(value);
    }
    let bare = !raw.is_empty()
        && raw
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '/' | '.' | '_' | '-' | ':' | '+'));
    bare.then(|| raw.to_string())
}

#[derive(Debug, PartialEq, Eq)]
enum EnvLine {
    Same,
    Changed(String),
    /// Holds an old name in a form the move does not rewrite.
    Left,
}

fn rewrite_env_line(line: &str, home: &Path) -> EnvLine {
    let untouched = || {
        if names_old(line) {
            EnvLine::Left
        } else {
            EnvLine::Same
        }
    };
    let (export, rest) = match line.strip_prefix("export ") {
        Some(r) => ("export ", r),
        None => ("", line),
    };
    let Some((key, raw)) = rest.split_once('=') else {
        return untouched();
    };
    if !is_env_key(key) {
        return untouched();
    }
    let Some(value) = unquote_env_value(raw) else {
        return untouched();
    };
    let new_key = rename_key(key);
    let new_value = rewrite_leading_dir(&value, home);
    if new_key == key && new_value == value {
        return untouched();
    }
    EnvLine::Changed(format!(
        "{export}{new_key}={}",
        crate::cli::agent::env_value(&new_value)
    ))
}

/// `~/.sprott/agent.env` and `~/.sprott/agents/*/agent.env`, sorted.
fn agent_env_files(data: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let top = data.join("agent.env");
    if top.is_file() {
        out.push(top);
    }
    if let Ok(entries) = fs::read_dir(data.join("agents")) {
        let mut agents: Vec<PathBuf> = entries
            .filter_map(|e| e.ok())
            .map(|e| e.path().join("agent.env"))
            .filter(|p| p.is_file())
            .collect();
        agents.sort();
        out.extend(agents);
    }
    out
}

fn rewrite_agent_env(
    home: &Path,
    data: &Path,
    file: &Path,
    left: &mut Vec<String>,
) -> Result<(), String> {
    let Ok(text) = fs::read_to_string(file) else {
        left.push(format!(
            "{} could not be read as text; it was left as it is.",
            tilde(home, file)
        ));
        return Ok(());
    };
    let mut out = String::with_capacity(text.len());
    let mut changed = false;
    for (i, piece) in text.split_inclusive('\n').enumerate() {
        let body = piece.trim_end_matches('\n');
        let (line, eol) = match body.strip_suffix('\r') {
            Some(l) => (l, &piece[l.len()..]),
            None => (body, &piece[body.len()..]),
        };
        let report_left = |left: &mut Vec<String>| {
            left.push(format!(
                "{} line {} still names SAFECLAW_ or ~/.safeclaw; edit it by hand.",
                tilde(home, file),
                i + 1
            ))
        };
        match rewrite_env_line(line, home) {
            EnvLine::Same => out.push_str(piece),
            EnvLine::Left => {
                report_left(left);
                out.push_str(piece);
            }
            EnvLine::Changed(new) => {
                if names_old(&new) {
                    report_left(left);
                }
                out.push_str(&new);
                out.push_str(eol);
                changed = true;
            }
        }
    }
    if !changed {
        return Ok(());
    }
    let rel = file.strip_prefix(data).unwrap_or(file);
    backup_copy(file, &data.join(PRE_2).join(rel))?;
    write_keeping_mode(file, out.as_bytes())
}

fn rewrite_setup_status(home: &Path, data: &Path) -> Result<(), String> {
    let path = data.join("setup").join("status.json");
    let Ok(bytes) = fs::read(&path) else {
        return Ok(());
    };
    let Ok(mut value) = serde_json::from_slice::<serde_json::Value>(&bytes) else {
        return Ok(());
    };
    if !rewrite_json_strings(&mut value, home) {
        return Ok(());
    }
    backup_copy(&path, &data.join(PRE_2).join("setup").join("status.json"))?;
    let body = serde_json::to_vec(&value).map_err(|e| format!("serialize status: {e}"))?;
    write_keeping_mode(&path, &body)
}

fn rewrite_json_strings(value: &mut serde_json::Value, home: &Path) -> bool {
    match value {
        serde_json::Value::String(s) => {
            let new = rewrite_dir_anywhere(s, home);
            let changed = new != *s;
            *s = new;
            changed
        }
        serde_json::Value::Array(items) => items
            .iter_mut()
            .fold(false, |acc, v| rewrite_json_strings(v, home) | acc),
        serde_json::Value::Object(map) => map
            .values_mut()
            .fold(false, |acc, v| rewrite_json_strings(v, home) | acc),
        _ => false,
    }
}

/// The old unit's `Environment=` lines, keys renamed and directory paths
/// rewritten. 1.x wrote them as `Environment="K=V"` with `\"` for a quote.
fn carry_unit_env(unit: &str, home: &Path) -> Vec<String> {
    let mut out = Vec::new();
    for line in unit.lines() {
        let Some(rest) = line.strip_prefix("Environment=") else {
            continue;
        };
        let parsed = rest
            .strip_prefix('"')
            .and_then(|r| r.strip_suffix('"'))
            .map(|r| r.replace("\\\"", "\""))
            .and_then(|r| {
                r.split_once('=')
                    .map(|(k, v)| (k.to_string(), v.to_string()))
            });
        match parsed {
            Some((k, v)) => out.push(crate::cli::service::systemd_env_line(
                &rename_key(&k),
                &rewrite_dir_anywhere(&v, home),
            )),
            None => out.push(line.to_string()),
        }
    }
    out
}

/// The old plist's `EnvironmentVariables`, keys renamed and directory paths
/// rewritten.
fn carry_plist_env(plist: &str, home: &Path) -> Vec<(String, String)> {
    let Some(start) = plist.find("<key>EnvironmentVariables</key>") else {
        return Vec::new();
    };
    let rest = &plist[start..];
    let Some(open) = rest.find("<dict>") else {
        return Vec::new();
    };
    let Some(close) = rest.find("</dict>") else {
        return Vec::new();
    };
    if close < open {
        return Vec::new();
    }
    static PAIR: once_cell::sync::Lazy<regex::Regex> = once_cell::sync::Lazy::new(|| {
        regex::Regex::new(r"<key>([^<]*)</key>\s*<string>([^<]*)</string>").expect("valid regex")
    });
    PAIR.captures_iter(&rest[open..close])
        .map(|c| {
            (
                rename_key(&xml_unescape(&c[1])),
                rewrite_dir_anywhere(&xml_unescape(&c[2]), home),
            )
        })
        .collect()
}

fn xml_unescape(s: &str) -> String {
    s.replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&quot;", "\"")
        .replace("&apos;", "'")
        .replace("&amp;", "&")
}


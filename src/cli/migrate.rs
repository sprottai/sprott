pub(crate) fn findings(home: &Path, unit_dir: &Path, launch_agents: &Path) -> Vec<String> {
    let mut out = Vec::new();
    match detect(home) {
        State::A => out.push("~/.safeclaw has not been moved to ~/.sprott yet; run: sprott up".into()),
        State::B => out.push("The move from ~/.safeclaw is not finished; run: sprott up".into()),
        State::C => out.push(
            "~/.safeclaw exists again beside ~/.sprott (written by a binary from before 2.0); Sprott 2.0 does not read it"
                .into(),
        ),
        State::D => out.push(
            "~/.safeclaw and ~/.sprott both exist; move ~/.sprott aside, then run: sprott up".into(),
        ),
        State::E => {}
    }
    for old in [
        unit_dir.join(OLD_UNIT),
        launch_agents.join(format!("{OLD_LABEL}.plist")),
    ] {
        if old.exists() {
            out.push(format!(
                "{} is a service file from before 2.0; the daemon is {}",
                tilde(home, &old),
                if cfg!(target_os = "macos") {
                    names::LAUNCHD_LABEL
                } else {
                    names::SYSTEMD_UNIT
                }
            ));
        }
    }
    if unit_dir.join(OLD_UNIT).exists() && unit_dir.join(names::SYSTEMD_UNIT).exists() {
        out.push(format!(
            "both {} and {} exist; only one daemon can hold the port",
            OLD_UNIT,
            names::SYSTEMD_UNIT
        ));
    }
    for file in agent_env_files(&names::data_dir_in(home)) {
        if fs::read_to_string(&file).is_ok_and(|t| names_old(&t)) {
            out.push(format!(
                "{} still names SAFECLAW_ or ~/.safeclaw; Sprott 2.0 reads SPROTT_ and ~/.sprott",
                tilde(home, &file)
            ));
        }
    }
    out
}


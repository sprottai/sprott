/// The loopback `host:port` the old daemon's control plane listens on, from
/// `<dir>/config.toml` key `daemon`, else the default port.
fn control_authority(dir: &Path) -> String {
    let default = format!("127.0.0.1:{}", crate::config::CONTROL_PORT);
    let Ok(text) = fs::read_to_string(dir.join("config.toml")) else {
        return default;
    };
    let Ok(table) = text.parse::<toml::Table>() else {
        return default;
    };
    table
        .get("daemon")
        .or_else(|| table.get("custodian"))
        .and_then(|v| v.as_str())
        .and_then(|s| url::Url::parse(s).ok())
        .and_then(|u| {
            let host = u.host_str()?.to_string();
            matches!(host.as_str(), "127.0.0.1" | "localhost" | "[::1]").then(|| {
                format!(
                    "{}:{}",
                    host,
                    u.port().unwrap_or(crate::config::CONTROL_PORT)
                )
            })
        })
        .unwrap_or(default)
}

fn read_pid(path: &Path) -> Option<u32> {
    fs::read_to_string(path).ok()?.trim().parse().ok()
}

fn read_json<T: serde::de::DeserializeOwned>(path: &Path) -> Option<T> {
    serde_json::from_slice(&fs::read(path).ok()?).ok()
}

fn write_json<T: Serialize>(path: &Path, value: &T) -> Result<(), String> {
    let mut body = serde_json::to_vec_pretty(value).map_err(|e| format!("serialize: {e}"))?;
    body.push(b'\n');
    write_atomic(path, &body, 0o600)
}

/// Write beside `path`, then rename over it: a reader sees the old or the new
/// file, never half of one.
fn write_atomic(path: &Path, bytes: &[u8], mode: u32) -> Result<(), String> {
    let name = path
        .file_name()
        .map(|n| n.to_string_lossy().to_string())
        .unwrap_or_default();
    let tmp = path.with_file_name(format!(".{name}.tmp.{}", std::process::id()));
    let mut opts = OpenOptions::new();
    opts.create(true).truncate(true).write(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        opts.mode(mode);
    }
    #[cfg(not(unix))]
    let _ = mode;
    let result = (|| {
        let mut f = opts.open(&tmp)?;
        f.write_all(bytes)?;
        f.sync_all()?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            fs::set_permissions(&tmp, fs::Permissions::from_mode(mode))?;
        }
        fs::rename(&tmp, path)
    })();
    result.map_err(|e| {
        let _ = fs::remove_file(&tmp);
        format!("write {}: {e}", path.display())
    })
}

fn write_keeping_mode(path: &Path, bytes: &[u8]) -> Result<(), String> {
    #[cfg(unix)]
    let mode = {
        use std::os::unix::fs::PermissionsExt;
        fs::metadata(path)
            .map(|m| m.permissions().mode() & 0o7777)
            .unwrap_or(0o600)
    };
    #[cfg(not(unix))]
    let mode = 0o600;
    write_atomic(path, bytes, mode)
}

fn private_dir(dir: &Path) -> Result<(), String> {
    fs::create_dir_all(dir).map_err(|e| format!("mkdir {}: {e}", dir.display()))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = fs::set_permissions(dir, fs::Permissions::from_mode(0o700));
    }
    Ok(())
}

/// Copy `src` to `dst` (mode kept), creating `pre-2.0/...` as needed.
fn backup_copy(src: &Path, dst: &Path) -> Result<(), String> {
    if let Some(parent) = dst.parent() {
        private_dir(parent)?;
    }
    fs::copy(src, dst)
        .map(|_| ())
        .map_err(|e| format!("copy {} to {}: {e}", src.display(), dst.display()))
}

/// Rename, or copy and remove when `dst` is on another file system.
fn move_file(src: &Path, dst: &Path) -> Result<(), String> {
    if let Some(parent) = dst.parent() {
        private_dir(parent)?;
    }
    if fs::rename(src, dst).is_ok() {
        return Ok(());
    }
    fs::copy(src, dst).map_err(|e| format!("copy {} to {}: {e}", src.display(), dst.display()))?;
    fs::remove_file(src).map_err(|e| format!("remove {}: {e}", src.display()))
}

/// Every file under `dir`, as paths relative to the data dir, sorted.
fn files_under(dir: &Path) -> Vec<String> {
    fn walk(dir: &Path, base: &Path, out: &mut Vec<String>) {
        let Ok(entries) = fs::read_dir(dir) else {
            return;
        };
        for e in entries.flatten() {
            let p = e.path();
            if p.is_dir() {
                walk(&p, base, out);
            } else if let Ok(rel) = p.strip_prefix(base) {
                out.push(rel.to_string_lossy().to_string());
            }
        }
    }
    let mut out = Vec::new();
    if let Some(base) = dir.parent() {
        walk(dir, base, &mut out);
    }
    out.sort();
    out
}

/// `~/x` for a path under `home`, else the path.
fn tilde(home: &Path, path: &Path) -> String {
    match path.strip_prefix(home) {
        Ok(rel) => format!("~/{}", rel.display()),
        Err(_) => path.display().to_string(),
    }
}

struct Lock {
    _file: fs::File,
    path: PathBuf,
}

impl Lock {
    /// `flock` on `~/.sprott-migrate.lock`; blocks while another command holds it.
    fn take(home: &Path) -> Result<Self, String> {
        let path = home.join(LOCK);
        let mut opts = OpenOptions::new();
        opts.create(true).truncate(false).write(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            opts.mode(0o600);
        }
        let file = opts.open(&path).map_err(|e| {
            format!(
                "Sprott 2.0 could not move ~/.safeclaw: open {}: {e}",
                path.display()
            )
        })?;
        #[cfg(unix)]
        rustix::fs::flock(&file, rustix::fs::FlockOperation::LockExclusive).map_err(|e| {
            format!(
                "Sprott 2.0 could not move ~/.safeclaw: lock {}: {e}",
                path.display()
            )
        })?;
        Ok(Lock { _file: file, path })
    }

    /// Remove the lock file once the move is finished. Only then: a command
    /// waiting on it re-reads the state and finds nothing to do, and no later
    /// command takes the lock (it finds nothing to do before locking), so no
    /// two commands can hold different lock files.
    fn release_finished(self) {
        let _ = fs::remove_file(&self.path);
    }
}

pub(crate) struct RealSys;

impl Sys for RealSys {
    fn answers(&self, authority: &str) -> bool {
        use std::net::ToSocketAddrs;
        authority
            .to_socket_addrs()
            .map(|addrs| {
                addrs.into_iter().any(|a| {
                    std::net::TcpStream::connect_timeout(&a, Duration::from_millis(400)).is_ok()
                })
            })
            .unwrap_or(false)
    }

    fn pid_live(&self, pid: u32) -> bool {
        crate::cli::human_action::pid_is_live(pid)
    }

    fn terminate(&self, pid: u32) {
        #[cfg(unix)]
        {
            extern "C" {
                fn kill(pid: i32, sig: i32) -> i32;
            }
            const SIGTERM: i32 = 15;
            unsafe {
                kill(pid as i32, SIGTERM);
            }
        }
        #[cfg(not(unix))]
        let _ = pid;
    }

    fn systemctl(&self, args: &[&str]) -> Result<(), String> {
        let mut all = vec!["--user"];
        all.extend_from_slice(args);
        tool("systemctl", &all)
    }

    fn launchctl(&self, args: &[&str]) -> Result<(), String> {
        tool("launchctl", args)
    }

    fn spawn_detached(&self, exe: &Path) -> Result<(), String> {
        crate::cli::service::spawn_detached_serve(exe).map(|_| ())
    }

    fn uid(&self) -> u32 {
        #[cfg(unix)]
        {
            extern "C" {
                fn getuid() -> u32;
            }
            unsafe { getuid() }
        }
        #[cfg(not(unix))]
        {
            0
        }
    }

    fn sleep(&self, d: Duration) {
        std::thread::sleep(d)
    }
}

fn tool(name: &str, args: &[&str]) -> Result<(), String> {
    let out = std::process::Command::new(name)
        .args(args)
        .output()
        .map_err(|e| format!("{name}: {e}"))?;
    if out.status.success() {
        Ok(())
    } else {
        Err(format!(
            "{name} {} failed: {}",
            args.join(" "),
            String::from_utf8_lossy(&out.stderr).trim()
        ))
    }
}

